import { describe, expect, it } from "vitest";
import { PERMISSIONS } from "@/lib/permissions/permissions";
import { PROPOSED_FINANCE_PERMISSION_KEYS } from "@/lib/finance/finance-architecture";

describe("FIN-01B finance permissions", () => {
  it("maps architecture keys to PERMISSIONS constants", () => {
    expect(PERMISSIONS.FINANCE_VIEW).toBe(PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_VIEW);
    expect(PERMISSIONS.FINANCE_STRUCTURE_MANAGE).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_STRUCTURE_MANAGE,
    );
    expect(PERMISSIONS.FINANCE_ADMIN).toBe(PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_ADMIN);
    expect(PERMISSIONS.FINANCE_BUDGET_VIEW).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_BUDGET_VIEW,
    );
    expect(PERMISSIONS.FINANCE_BUDGET_MANAGE).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_BUDGET_MANAGE,
    );
    expect(PERMISSIONS.FINANCE_APPROVE).toBe(PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_APPROVE);
    expect(PERMISSIONS.FINANCE_ACTUAL_VIEW).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_ACTUAL_VIEW,
    );
    expect(PERMISSIONS.FINANCE_ACTUAL_MANAGE).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_ACTUAL_MANAGE,
    );
    expect(PERMISSIONS.FINANCE_FORECAST_VIEW).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_FORECAST_VIEW,
    );
    expect(PERMISSIONS.FINANCE_FORECAST_MANAGE).toBe(
      PROPOSED_FINANCE_PERMISSION_KEYS.FINANCE_FORECAST_MANAGE,
    );
  });

  it("keeps person compensation permissions separate from finance.view", () => {
    expect(PERMISSIONS.FINANCE_VIEW).not.toBe(PERMISSIONS.PEOPLE_FINANCE_VIEW);
    expect(PERMISSIONS.FINANCE_VIEW).not.toBe(PERMISSIONS.BILLING_VIEW);
  });
});
