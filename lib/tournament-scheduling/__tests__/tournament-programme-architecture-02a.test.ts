/**
 * SCE-TOURNAMENT-PLANNER-02A — programme architecture guardrails.
 */

import { describe, expect, it } from "vitest";
import {
  ADVANCED_FAIRNESS_OPTIMISER_IMPLEMENTED,
  ADVANCED_FORMAT_MAY_REQUIRE_PLAYING_FORMAT,
  ADVANCED_TOURNAMENT_PROGRAMME_GENERATION,
  ARBITRARY_PLAYERS_PER_SIDE_PRESET_ONLY,
  DEFAULT_PLAYING_FORMAT_ASSIGNED,
  EXISTING_TOURNAMENTS_VALID,
  LEGACY_TOURNAMENT_FORMAT_REQUIRED,
  NORMAL_TOURNAMENT_FORMAT_REQUIRED,
  FIXTURE_PROGRAMME_ASSIGNMENT_RELATIONSHIP_DEFINED,
  FULL_TEAM_FUTURE_READY,
  HARD_CONSTRAINTS_DOMINATE_FAIRNESS,
  HEURISTIC_FAILURE_NEQ_INFEASIBLE,
  IN_ROUND_PHASE_CONTRACT_DEFINED,
  IN_ROUND_PHASE_IMPLEMENTED,
  MULTIPLE_LOGICAL_PITCHES_PER_PHYSICAL_RESOURCE_FUTURE_READY,
  NON_FIXTURE_ASSIGNMENTS_FUTURE_READY,
  ONE_CANONICAL_PROGRAMME,
  PARALLEL_SCHEDULE_TRUTH_CREATED,
  PARENT_CAPACITY_CONTRACT_DEFINED,
  PARTICIPANT_NEQ_PLAYING_UNIT,
  PLAYERS_PER_SIDE_BOUND_REVIEW_DEFERRED_TO_02B,
  PLAYERS_PER_SIDE_MAX,
  PLAYERS_PER_SIDE_MIN,
  PLAYERS_PER_SIDE_PRODUCT_MAX,
  PLAYERS_PER_SIDE_TECHNICAL_BOUND_MAX,
  PLAYING_FORMAT_GENERIC,
  PLAYING_FORMAT_HARD_CODED_3V3_6V6_ENUM,
  PLAYING_FORMAT_HARD_CODED_SWISS_ENUM,
  PLAYING_FORMAT_OPTIONAL_BY_DEFAULT,
  PLAYING_FORMAT_REQUIRED_FOR_LEGACY_TOURNAMENTS,
  PLAYING_FORMAT_REQUIRED_GLOBALLY,
  SILENT_FORMAT_INFERENCE,
  TECHNICAL_BOUND_IS_PRODUCT_RULE,
  UNSPECIFIED_PLAYING_FORMAT_VALID,
  ROTATION_COEXISTS_WITH_SMART_MIX,
  ROTATION_FIRST_CLASS_FUTURE_FORMAT,
  ROTATION_FORCED_INTO_SMART_MIX,
  ROTATION_GENERATOR_IMPLEMENTED,
  ROUND_MODEL_DEFINED,
  SFV_SPECIFIC_TYPES_IN_CORE_DOMAIN,
  SUBTEAM_FUTURE_READY,
  TEAM_SPIELPLAN_DERIVED,
  TIMING_CONCEPTS,
  TIMING_CONCEPTS_REMAIN_DISTINCT,
  TOURNAMENT_PITCH_IS_LOGICAL,
  TOURNAMENT_PITCH_NEQ_FACILITY_RESOURCE,
  TOURNAMENT_PITCH_PLAYING_FORMAT_RELATIONSHIP_DEFINED,
  TOURNAMENT_PLANNER_01_BACKWARD_COMPATIBLE,
  TOURNAMENT_PLANNER_02_PACKAGES,
  TOURNAMENT_PROGRAMME_PIPELINE_STAGES,
  TOURNAMENT_STATION_CONTRACT_DEFINED,
  TOURNAMENT_STATION_PERSISTENCE_IMPLEMENTED,
  TP01_EVOLUTION_NOT_REPLACEMENT,
  TP01_GENERATORS_PRESERVED,
  TP01_OUTPUTS_PRESERVED,
  TP01_SCHEDULER_PRESERVED,
  UNSPECIFIED_PLAYING_FORMAT_BACKWARD_COMPATIBLE,
  formatPlayersPerSideDisplayLabel,
  isPlayersPerSideInValidationBand,
} from "../tournament-programme-architecture";

describe("SCE Tournament Programme — 02A contracts", () => {
  it("records canonical programme pipeline and TP01 evolution", () => {
    expect(ADVANCED_TOURNAMENT_PROGRAMME_GENERATION).toBe("CANONICAL_TARGET");
    expect(TOURNAMENT_PROGRAMME_PIPELINE_STAGES).toEqual([
      "PARTICIPANTS",
      "PLAYING_FORMATS",
      "PLAYING_UNITS",
      "ROUNDS",
      "ASSIGNMENTS",
      "PITCHES_AND_STATIONS",
      "TIMING",
      "SPIELPLAN",
    ]);
    expect(TP01_EVOLUTION_NOT_REPLACEMENT).toBe(true);
    expect(ONE_CANONICAL_PROGRAMME).toBe(true);
    expect(TEAM_SPIELPLAN_DERIVED).toBe(true);
    expect(PARALLEL_SCHEDULE_TRUTH_CREATED).toBe(false);
  });

  it("preserves logical TournamentPitch invariants", () => {
    expect(TOURNAMENT_PITCH_IS_LOGICAL).toBe(true);
    expect(TOURNAMENT_PITCH_NEQ_FACILITY_RESOURCE).toBe(true);
    expect(MULTIPLE_LOGICAL_PITCHES_PER_PHYSICAL_RESOURCE_FUTURE_READY).toBe(true);
    expect(TOURNAMENT_PITCH_PLAYING_FORMAT_RELATIONSHIP_DEFINED).toBe(true);
  });

  it("uses generic playersPerSide playing format — not hard-coded Swiss enums", () => {
    expect(PLAYING_FORMAT_GENERIC).toBe(true);
    expect(PLAYING_FORMAT_HARD_CODED_SWISS_ENUM).toBe(false);
    expect(PLAYING_FORMAT_HARD_CODED_3V3_6V6_ENUM).toBe(false);
    expect(ARBITRARY_PLAYERS_PER_SIDE_PRESET_ONLY).toBe(false);
    expect(SFV_SPECIFIC_TYPES_IN_CORE_DOMAIN).toBe(false);
    expect(formatPlayersPerSideDisplayLabel(3)).toBe("3v3");
    expect(formatPlayersPerSideDisplayLabel(11)).toBe("11v11");
    expect(isPlayersPerSideInValidationBand(3)).toBe(true);
    expect(isPlayersPerSideInValidationBand(11)).toBe(true);
    expect(isPlayersPerSideInValidationBand(0)).toBe(false);
    expect(isPlayersPerSideInValidationBand(PLAYERS_PER_SIDE_MAX + 1)).toBe(false);
    expect(PLAYERS_PER_SIDE_MIN).toBeGreaterThanOrEqual(1);
    expect(PLAYERS_PER_SIDE_MAX).toBeGreaterThanOrEqual(11);
    expect(PLAYERS_PER_SIDE_PRODUCT_MAX).toBeNull();
    expect(PLAYERS_PER_SIDE_TECHNICAL_BOUND_MAX).toBe(22);
    expect(TECHNICAL_BOUND_IS_PRODUCT_RULE).toBe(false);
    expect(PLAYERS_PER_SIDE_BOUND_REVIEW_DEFERRED_TO_02B).toBe(true);
  });

  it("locks PlayingFormat optionality — optional by default, no defaults or silent inference", () => {
    expect(PLAYING_FORMAT_OPTIONAL_BY_DEFAULT).toBe(true);
    expect(PLAYING_FORMAT_REQUIRED_GLOBALLY).toBe(false);
    expect(UNSPECIFIED_PLAYING_FORMAT_VALID).toBe(true);
    expect(DEFAULT_PLAYING_FORMAT_ASSIGNED).toBe(false);
    expect(SILENT_FORMAT_INFERENCE).toBe(false);
    expect(NORMAL_TOURNAMENT_FORMAT_REQUIRED).toBe(false);
    expect(LEGACY_TOURNAMENT_FORMAT_REQUIRED).toBe(false);
    expect(ADVANCED_FORMAT_MAY_REQUIRE_PLAYING_FORMAT).toBe(true);
    expect(EXISTING_TOURNAMENTS_VALID).toBe(true);
  });

  it("records participant vs playing unit and rotation boundaries", () => {
    expect(PARTICIPANT_NEQ_PLAYING_UNIT).toBe(true);
    expect(FULL_TEAM_FUTURE_READY).toBe(true);
    expect(SUBTEAM_FUTURE_READY).toBe(true);
    expect(PARENT_CAPACITY_CONTRACT_DEFINED).toBe(true);
    expect(ROTATION_FIRST_CLASS_FUTURE_FORMAT).toBe(true);
    expect(ROTATION_FORCED_INTO_SMART_MIX).toBe(false);
    expect(ROTATION_GENERATOR_IMPLEMENTED).toBe(false);
    expect(ROTATION_COEXISTS_WITH_SMART_MIX).toBe(true);
  });

  it("defines programme assignments, stations, rounds, and timing without implementing them", () => {
    expect(FIXTURE_PROGRAMME_ASSIGNMENT_RELATIONSHIP_DEFINED).toBe(true);
    expect(NON_FIXTURE_ASSIGNMENTS_FUTURE_READY).toBe(true);
    expect(TOURNAMENT_STATION_CONTRACT_DEFINED).toBe(true);
    expect(TOURNAMENT_STATION_PERSISTENCE_IMPLEMENTED).toBe(false);
    expect(ROUND_MODEL_DEFINED).toBe(true);
    expect(IN_ROUND_PHASE_CONTRACT_DEFINED).toBe(true);
    expect(IN_ROUND_PHASE_IMPLEMENTED).toBe(false);
    expect(TIMING_CONCEPTS_REMAIN_DISTINCT).toBe(true);
    expect(TIMING_CONCEPTS).toContain("IN_ROUND_PHASE");
    expect(TIMING_CONCEPTS).toContain("TOURNAMENT_BREAK");
    expect(new Set(TIMING_CONCEPTS).size).toBe(TIMING_CONCEPTS.length);
  });

  it("records fairness model and backward compatibility", () => {
    expect(HARD_CONSTRAINTS_DOMINATE_FAIRNESS).toBe(true);
    expect(HEURISTIC_FAILURE_NEQ_INFEASIBLE).toBe(true);
    expect(ADVANCED_FAIRNESS_OPTIMISER_IMPLEMENTED).toBe(false);
    expect(UNSPECIFIED_PLAYING_FORMAT_BACKWARD_COMPATIBLE).toBe(true);
    expect(PLAYING_FORMAT_REQUIRED_FOR_LEGACY_TOURNAMENTS).toBe(false);
    expect(TOURNAMENT_PLANNER_01_BACKWARD_COMPATIBLE).toBe(true);
    expect(TP01_GENERATORS_PRESERVED).toBe(true);
    expect(TP01_SCHEDULER_PRESERVED).toBe(true);
    expect(TP01_OUTPUTS_PRESERVED).toBe(true);
  });

  it("maps 02A–02H package boundaries", () => {
    expect(TOURNAMENT_PLANNER_02_PACKAGES["02A"]).toMatch(/architecture/i);
    expect(TOURNAMENT_PLANNER_02_PACKAGES["02D"]).toMatch(/Rotation/i);
    expect(TOURNAMENT_PLANNER_02_PACKAGES["02H"]).toMatch(/Spielplan/i);
  });
});
